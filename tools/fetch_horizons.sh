#!/bin/sh
# SPACETIME LAB — tools/fetch_horizons.sh
#
# Fetches every raw NASA JPL Horizons response the EPHEM catalog needs
# (src/space/ephem_data.c) and stores them verbatim under data/horizons/,
# one file per (target, epoch). Nothing is typed in by hand: ephem_data.c
# is generated from these files by tools/gen_ephem.py. Also (re)writes
# data/horizons/MANIFEST.md with every query URL, the UTC time it was
# fetched, and the Horizons "source: DE..." line found in the response.
#
# Usage: tools/fetch_horizons.sh   (run from anywhere; paths are relative
# to this script's directory, i.e. the spacetime/ project root's parent).
#
# Polite fetching: one request at a time, ~0.5s sleep between requests.
# Two epochs per target:
#   e0 = 2000-01-01 12:00 TDB (J2000.0, JD 2451545.0)
#   e1 = 2026-09-27 00:00 TDB
#
# Targets: "own-vector" bodies (Sun, planets, moons, dwarfs, asteroids —
# each queried by its Horizons body/small-body id, giving both the state
# vector and the OBJ_DATA physical-parameters block with GM + radius) and
# "system" barycentres (Mercury..Neptune system barycentres 1-8, Pluto
# system barycentre 9 — queried for the barycentric state vector used
# when moons are off; Horizons never reports a system GM for these, so
# gen_ephem.py sums the component GMs from the own-vector fetches
# instead, and records that in MANIFEST.md).

set -eu

SCRIPT_DIR=$(cd "$(dirname "$0")" && pwd)
ROOT_DIR=$(dirname "$SCRIPT_DIR")
OUT_DIR="$ROOT_DIR/data/horizons"
MANIFEST="$OUT_DIR/MANIFEST.md"
BASE="https://ssd.jpl.nasa.gov/api/horizons.api"

mkdir -p "$OUT_DIR"

# --- epochs ----------------------------------------------------------------
# epoch tag : start time : stop time (start + 1 minute, so VEC_TABLE=2 with
# STEP_SIZE=1 emits exactly two rows one minute apart; gen_ephem.py takes
# the first).
E0_TAG=e0; E0_START="2000-01-01%2012:00"; E0_STOP="2000-01-01%2012:01"
E1_TAG=e1; E1_START="2026-09-27%2000:00"; E1_STOP="2026-09-27%2000:01"

# --- own-vector catalog targets ---------------------------------------------
# "name|command|small(0/1)" — small=1 targets get a URL-encoded trailing
# semicolon (%3B) appended to the command so Horizons resolves them via the
# small-body (SBDB) lookup instead of the major-body table; a literal ';'
# in the query string is otherwise swallowed as a parameter separator by
# the API gateway (confirmed empirically on this endpoint).
BODIES="
sun|10|0
mercury|199|0
venus|299|0
earth|399|0
mars|499|0
jupiter|599|0
saturn|699|0
uranus|799|0
neptune|899|0
moon|301|0
io|501|0
europa|502|0
ganymede|503|0
callisto|504|0
mimas|601|0
enceladus|602|0
tethys|603|0
dione|604|0
rhea|605|0
titan|606|0
iapetus|608|0
miranda|705|0
ariel|701|0
umbriel|702|0
titania|703|0
oberon|704|0
triton|801|0
charon|901|0
pluto|999|0
ceres|1|1
eris|136199|1
makemake|136472|1
haumea|136108|1
vesta|4|1
pallas|2|1
hygiea|10|1
interamnia|704|1
davida|511|1
"

# name|barycentre-id (Horizons major-body barycentre numbering 1-9)
SYSTEMS="
mercury|1
venus|2
earth|3
mars|4
jupiter|5
saturn|6
uranus|7
neptune|8
pluto|9
"

: > "$MANIFEST"
{
  echo "# Horizons fetch manifest"
  echo
  echo "Generated by \`tools/fetch_horizons.sh\`. Every query URL below was"
  echo "actually issued to \`$BASE\` at the UTC time shown; the response is"
  echo "stored verbatim in this directory. Source: NASA JPL Horizons"
  echo "(https://ssd.jpl.nasa.gov/horizons/)."
  echo
} >> "$MANIFEST"

fetch_one () {
  # $1 = output basename (no extension), $2 = COMMAND value (already
  # percent-escaped where needed), $3 = start time, $4 = stop time,
  # $5 = epoch tag (for the log line)
  base="$1"; cmd="$2"; start="$3"; stop="$4"; etag="$5"
  out="$OUT_DIR/${base}_${etag}.txt"
  url="${BASE}?format=text&COMMAND='${cmd}'&OBJ_DATA='YES'&MAKE_EPHEM='YES'&EPHEM_TYPE='VECTORS'&CENTER='500@0'&START_TIME='${start}'&STOP_TIME='${stop}'&STEP_SIZE='1'&REF_PLANE='ECLIPTIC'&REF_SYSTEM='ICRF'&OUT_UNITS='KM-S'&VEC_TABLE='2'&CSV_FORMAT='YES'&TIME_TYPE='TDB'"
  when=$(date -u +"%Y-%m-%dT%H:%M:%SZ")
  ok=1
  if ! curl -sS -m 30 "$url" > "$out.tmp" 2> "$out.err"; then
    ok=0
  fi
  if [ "$ok" = 1 ] && grep -q '\$\$SOE' "$out.tmp" 2>/dev/null; then
    mv "$out.tmp" "$out"
    rm -f "$out.err"
    src=$(grep -m1 -o 'source: [A-Za-z0-9#]*' "$out" | head -1 | sed 's/source: //')
    status="OK (source: ${src:-unknown})"
  else
    mv "$out.tmp" "${out}.FAILED" 2>/dev/null || true
    status="FAILED (see ${base}_${etag}.txt.err / .FAILED)"
  fi
  {
    echo "- \`${base}\` epoch ${etag} — ${status}"
    echo "  fetched: ${when}"
    echo "  url: \`${url}\`"
  } >> "$MANIFEST"
  echo "[$when] ${base} ${etag}: ${status}"
  sleep 0.5
}

echo "$BODIES" | while IFS='|' read -r name cmd small; do
  [ -z "$name" ] && continue
  if [ "$small" = "1" ]; then
    q="${cmd}%3B"
  else
    q="${cmd}"
  fi
  fetch_one "$name" "$q" "$E0_START" "$E0_STOP" "$E0_TAG"
  fetch_one "$name" "$q" "$E1_START" "$E1_STOP" "$E1_TAG"
done

echo "$SYSTEMS" | while IFS='|' read -r name bid; do
  [ -z "$name" ] && continue
  fetch_one "${name}_sys" "$bid" "$E0_START" "$E0_STOP" "$E0_TAG"
  fetch_one "${name}_sys" "$bid" "$E1_START" "$E1_STOP" "$E1_TAG"
done

{
  echo
  echo "## Notes"
  echo
  echo "- Time system: TIME_TYPE=TDB, confirmed per-response by the header"
  echo "  line \`Start time      : A.D. ... TDB\`."
  echo "- Frame: REF_PLANE=ECLIPTIC, REF_SYSTEM=ICRF (\"Ecliptic of J2000.0\","
  echo "  X-axis ICRF), CENTER=500@0 (Solar System Barycenter) — vectors are"
  echo "  already barycentric, no origin shift needed beyond a residual check."
  echo "- System barycentre fetches (\`*_sys_e?.txt\`) carry no GM in their"
  echo "  OBJ_DATA block (Horizons has no mass concept for a barycentre);"
  echo "  \`tools/gen_ephem.py\` computes gm_system by summing the fetched"
  echo "  component GMs (planet + its cataloged moons) and records the"
  echo "  composition in ephem_data.c's header comment."
  echo "- GM for Mercury/Venus system barycentres equals the planet GM"
  echo "  (no cataloged moons); fetched anyway per spec for completeness."
  echo "- Dropped from the compiled catalog (fetched anyway, see"
  echo "  eris_e0.txt / makemake_e0.txt / haumea_e0.txt / davida_e0.txt):"
  echo "  Eris (136199), Makemake (136472), Haumea (136108) and Davida"
  echo "  (511) all come back \`GM= n.a.\` from the Horizons small-body"
  echo "  lookup (Eris/Makemake/Haumea also \`RAD= n.a.\`); per program"
  echo "  rule R8 (no fabricated references) tools/gen_ephem.py refuses"
  echo "  to fill these in from outside knowledge and leaves the four"
  echo "  bodies out of src/space/ephem_data.c. The raw responses are"
  echo "  kept here so the n.a. result is independently checkable."
} >> "$MANIFEST"

echo "Done (Horizons). Manifest: $MANIFEST"

# ---------------------------------------------------------------------------
# EPHEM-2: NAIF gravity-field (J2/J4 + reference radius) and pole (PCK)
# sources for the oblateness upgrade. Separate directory (data/naif/),
# separate manifest, so the Horizons fetch above stays untouched/rerunnable
# on its own.
# ---------------------------------------------------------------------------
NAIF_DIR="$ROOT_DIR/data/naif"
NAIF_MANIFEST="$NAIF_DIR/MANIFEST.md"
mkdir -p "$NAIF_DIR"

# Satellite-ephemeris comment files: same kernel "source" tags Horizons
# already reported for these bodies' vectors (jup365, sat441l -> sat441,
# ura184, nep098), so the J2/J4 used here are the ones that actually
# produced the moon positions we're comparing against.
NAIF_CMT="
jup365|https://naif.jpl.nasa.gov/pub/naif/generic_kernels/spk/satellites/jup365.cmt
sat441|https://naif.jpl.nasa.gov/pub/naif/generic_kernels/spk/satellites/sat441.cmt
ura184|https://naif.jpl.nasa.gov/pub/naif/generic_kernels/spk/satellites/ura184_part-1.cmt
nep098|https://naif.jpl.nasa.gov/pub/naif/generic_kernels/spk/satellites/nep098_part-1.cmt
"
PCK_URL="https://naif.jpl.nasa.gov/pub/naif/generic_kernels/pck/pck00011.tpc"

: > "$NAIF_MANIFEST"
{
  echo "# NAIF fetch manifest (EPHEM-2: oblateness + pole orientation)"
  echo
  echo "Generated by \`tools/fetch_horizons.sh\`. Giant-planet J2/J4/reference"
  echo "radius come from the SPICE satellite-ephemeris kernel comment files"
  echo "(the .cmt sidecar of the .bsp actually used for that body's moon"
  echo "positions, matched by the Horizons source tag already recorded in"
  echo "data/horizons/MANIFEST.md). Pole RA/Dec (constant term, ICRF"
  echo "equatorial) come from the NAIF generic PCK. Earth's J2 and every"
  echo "reference radius except the giants' gravity-field radius reuse"
  echo "data already fetched into data/horizons/ (see there for those URLs)."
  echo
} >> "$NAIF_MANIFEST"

fetch_naif () {
  base="$1"; url="$2"
  out="$NAIF_DIR/${base}.txt"
  when=$(date -u +"%Y-%m-%dT%H:%M:%SZ")
  if curl -sS -m 60 "$url" > "$out.tmp" 2> "$out.err" && [ -s "$out.tmp" ]; then
    mv "$out.tmp" "$out"
    rm -f "$out.err"
    st="OK"
  else
    mv "$out.tmp" "${out}.FAILED" 2>/dev/null || true
    st="FAILED (see ${base}.txt.err / .FAILED)"
  fi
  {
    echo "- \`${base}\` — ${st}"
    echo "  fetched: ${when}"
    echo "  url: <${url}>"
  } >> "$NAIF_MANIFEST"
  echo "[$when] naif ${base}: ${st}"
  sleep 0.5
}

echo "$NAIF_CMT" | while IFS='|' read -r base url; do
  [ -z "$base" ] && continue
  fetch_naif "$base" "$url"
done
fetch_naif "pck00011" "$PCK_URL"

{
  echo
  echo "## Exact lines used (recorded here so a re-fetch can be diffed"
  echo "## against what tools/gen_ephem.py actually parsed)"
  echo
  echo '```'
  echo "jup365.txt (JUP365.26 block, only version in file):"
  grep -n "^ J50[0-9]\|^ S1RADEQ\|RADIUS " "$NAIF_DIR/jup365.txt" | grep -E "J502|J504|RADIUS" | head -2
  echo
  echo "sat441.txt (SAT441.24 block, only version in file):"
  grep -n "J602\|J604\|RADIUS" "$NAIF_DIR/sat441.txt" | head -2
  echo
  echo "ura184.txt (URA184 block specifically -- the file also carries"
  echo "older URA182.21/URA117/URA115 solutions earlier in the same file"
  echo "with different J2/J4; the last 'Satellite Ephemeris: URA184'"
  echo "section is the one that matches our fetched Horizons vectors):"
  grep -n "Satellite Ephemeris: URA184" "$NAIF_DIR/ura184.txt"
  awk '/Satellite Ephemeris: URA184/{f=1} f && /J702/{print; c++; if(c==1) exit}' "$NAIF_DIR/ura184.txt"
  echo
  echo "nep098_part-1.txt (NEP098 block, only version in file):"
  grep -n "J802\|J804\|RADIUS" "$NAIF_DIR/nep098_part-1.txt" | head -2
  echo '```'
} >> "$NAIF_MANIFEST"

echo "Done (NAIF). Manifest: $NAIF_MANIFEST"
